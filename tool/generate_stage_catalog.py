#!/usr/bin/env python3
"""Writes lib/stage_catalog.dart: the fixed answers for stages 1-1000.

Stages 1-10 keep their original answers. Stages 11-1000 use every other
3-5 letter word in the catalogue exactly once, ordered so that early areas
lean on 3-letter words and later areas move to 4- and 5-letter words.

The output is committed and must stay stable after release: a saved,
unfinished stage is dropped if its answer changes. Re-run only before a
release, and never just to pick up newly added words.
"""
import random
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIRST = ["さくら", "うさぎ", "すみれ", "たんぽぽ", "きつね",
         "どんぐり", "もみじ", "ひまわり", "いちご", "あじさい"]
TOTAL = 1000


def catalogue():
    text = (ROOT / "lib" / "game.dart").read_text() + (ROOT / "lib" / "word_data.dart").read_text()
    seen, words = set(), []
    for w in re.findall(r"Word(?:\.entry)?\(\s*'([^']+)'", text):
        if 3 <= len(w) <= 5 and w not in seen:
            seen.add(w)
            words.append(w)
    return words


def main():
    rng = random.Random(20261128)
    pool = {n: [w for w in catalogue() if len(w) == n and w not in FIRST] for n in (3, 4, 5)}
    for n in pool:
        rng.shuffle(pool[n])
    total = sum(len(v) for v in pool.values())
    assert len(FIRST) + total == TOTAL, (len(FIRST), total)

    # Share of each length wanted at a point of the journey (0 = start, 1 = end).
    def weights(t):
        return {3: max(0.04, 0.85 - 0.95 * t), 4: 0.35 + 0.15 * (1 - abs(2 * t - 1)), 5: 0.05 + 0.95 * t}

    totals = {n: len(v) for n, v in pool.items()}
    # Cumulative target per length, scaled so every word is used by the end.
    steps = TOTAL - len(FIRST)
    cum = {n: [0.0] for n in pool}
    for i in range(steps):
        w = weights(i / (steps - 1))
        for n in pool:
            cum[n].append(cum[n][-1] + w[n])
    for n in pool:
        scale = totals[n] / cum[n][-1]
        cum[n] = [c * scale for c in cum[n]]

    used = {n: 0 for n in pool}
    order = []
    for i in range(steps):
        # Pick the length that is furthest behind its target.
        n = max((m for m in pool if used[m] < totals[m]),
                key=lambda m: cum[m][i + 1] - used[m])
        order.append(pool[n][used[n]])
        used[n] += 1

    answers = FIRST + order
    assert len(answers) == len(set(answers)) == TOTAL
    lines = ["// GENERATED by tool/generate_stage_catalog.py. Do not edit by hand.",
             "// Stable stage answers: changing one drops an unfinished save of that stage.",
             "",
             "const stageAnswers = <String>["]
    lines += [f"  '{w}'," for w in answers]
    lines += ["];", ""]
    (ROOT / "lib" / "stage_catalog.dart").write_text("\n".join(lines))
    for a in range(0, TOTAL, 200):
        chunk = answers[a:a + 200]
        print(a + 1, {n: sum(len(w) == n for w in chunk) for n in (3, 4, 5)})


if __name__ == "__main__":
    main()
